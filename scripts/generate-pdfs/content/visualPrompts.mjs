export function visualPromptsHtml() {
  let n = 0;
  const sections = categories
    .map((cat) => {
      const cards = cat.items
        .map((item) => {
          n += 1;
          return `<div class="card">
            <span class="num">${n}</span><span class="label">${cat.label}</span>
            <div class="prompt">${item.prompt}</div>
            <div class="tip">💡 ${item.tip}</div>
          </div>`;
        })
        .join("\n");
      return `<div class="page"><h2>${cat.label}</h2>${cards}</div>`;
    })
    .join("\n");

  return `
  <div class="cover">
    <div class="kicker">ملتقى · منتجات رقمية بالذكاء الاصطناعي</div>
    <h1>برومبتات احترافية<br/>لتوليد وتعديل الصور والفيديو</h1>
    <p>أكثر من 30 برومبتًا بمواصفات استوديو حقيقية — إضاءة، عدسات، تدرجات لونية — لتوليد وتعديل الصور والفيديو بجودة استوديوهات الإنتاج الاحترافية.</p>
    <div class="brand">ملتقى — Multaqa</div>
  </div>
  ${sections}
  <div class="page">
    <h2>كيف تستخدم هذه الحزمة</h2>
    <p>هذه البرومبتات مكتوبة لتعمل مع أدوات توليد الصور والفيديو الشائعة (مثل Midjourney وDALL·E وRunway وأدوات مشابهة). استبدل الأقواس مثل <strong>[اسم المنتج]</strong> أو <strong>[صف المشهد]</strong> بوصفك الخاص.</p>
    <p>المصطلحات التقنية المذكورة (نوع الإضاءة، مقاس العدسة، نسبة العرض) هي ما يفرّق بين نتيجة عادية ونتيجة تبدو فعلًا بجودة استوديو احترافي — لا تحذفها حتى لو بدت تفصيلية.</p>
    <div class="footer-note">© ملتقى. للاستخدام الشخصي فقط. يُرجى عدم إعادة بيع أو توزيع هذا الملف.</div>
  </div>
  `;
}
