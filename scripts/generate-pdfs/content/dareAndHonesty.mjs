function buildItems() {
  const items = [];
  for (let i = 0; i < truths.length; i++) {
    items.push({ type: "truth", text: truths[i] });
    items.push({ type: "dare", text: dares[i] });
  }
  return items;
}

export function dareAndHonestyHtml() {
  const items = buildItems();
  const slides = items
    .map((item, i) => {
      const badgeClass = item.type === "truth" ? "truth" : "dare";
      const badgeLabel = item.type === "truth" ? "صراحة" : "جرأة";
      return `<div class="slide slide-bg-dare">
        <div class="slide-frame"></div>
        <div class="slide-brand">ملتقى — جرأة وصراحة</div>
        <span class="slide-type-badge ${badgeClass}">${badgeLabel}</span>
        <div class="slide-question">${item.text}</div>
        <div class="slide-number">${i + 1} / ${items.length}</div>
      </div>`;
    })
    .join("\n");

  return `
  <div class="slide slide-bg-dare">
    <div class="slide-frame"></div>
    <div class="slide-kicker">ملتقى · ألعاب للأزواج</div>
    <div class="slide-cover-title">جرأة وصراحة</div>
    <div class="slide-cover-sub">20 سؤال صراحة و20 تحدي جرأة يتبادلان في كل شريحة — أسئلة وطلبات محترمة، بلا إحراج، فقط قرب أكثر.</div>
  </div>
  ${slides}
  <div class="slide slide-bg-dare">
    <div class="slide-frame"></div>
    <div class="slide-cover-title" style="font-size:40px">انتهت اللعبة 🔥</div>
    <div class="slide-cover-sub">الجرأة والصراحة أقرب طريق لفهم بعضكما أكثر. ملتقى — Multaqa</div>
  </div>
  `;
}
